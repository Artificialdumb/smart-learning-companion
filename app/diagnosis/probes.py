def profile_for(description):
    # shortcut: 按已覆盖的课程描述选择固定题组，新增学科前须补充并审阅题组。
    for cues, profile in (
        (("交集",), "intersection"),
        (("列不等式", "实际限制"), "constraint"),
        (("不等式性质", "负数乘除"), "inequality"),
        (("列方程",), "model"),
        (("消元",), "system"),
        (("一元一次方程",), "equation"),
        (("去括号", "同类项", "化简"), "expressions"),
        (("数量关系", "代入求值", "整式解释", "解释表达式"), "quantity"),
    ):
        if any(cue in description for cue in cues):
            return profile
    return None


def questions_for(description):
    profile = profile_for(description)
    return [
        {"question_id": f"{profile}-{dimension}", "dimension": dimension,
         "prompt": prompt, "options": [
             {"option_id": str(i), "text": text} for i, text in enumerate(options)
         ], "answer_id": str(answer), "explanation": explanation}
        for dimension, (prompt, options, answer, explanation)
        in zip(DIMENSIONS, PROFILES.get(profile, ()))
    ]
